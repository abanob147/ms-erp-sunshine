-- MS ERP starter schema for Supabase
-- Run this in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.import_shipments (
  id bigint generated by default as identity primary key,
  name text not null,
  expected_arrival date,
  container_number text,
  bl_number text,
  invoice_value numeric(14,2) not null default 0,
  invoice_currency text not null default 'USD' check (invoice_currency in ('USD','CNY','EGP')),
  landed_cost_egp numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.items (
  id bigint generated by default as identity primary key,
  sku text unique,
  name text not null,
  unit text,
  opening_quantity numeric(14,3) not null default 0,
  created_at timestamptz not null default now()
);
alter table public.import_shipments enable row level security;
alter table public.items enable row level security;
drop policy if exists "authenticated users manage shipments" on public.import_shipments;
create policy "authenticated users manage shipments" on public.import_shipments
  for all to authenticated using (true) with check (true);
drop policy if exists "authenticated users manage items" on public.items;
create policy "authenticated users manage items" on public.items
  for all to authenticated using (true) with check (true);
